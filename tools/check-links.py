#!/usr/bin/env python3
"""Check every external link on the site for 404s.

Only listings that actually resolve are published, so the pages never advertise
dead endpoints. Bot-blocked hosts (npm, LinkedIn, ResearchGate answer 403/999 to
curl) are reported separately as UNKNOWN rather than treated as broken.

Usage:
    python3 tools/check-links.py            # check and report
    python3 tools/check-links.py --write    # also refresh tools/link-status.txt
"""
from __future__ import annotations

import concurrent.futures
import html
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
STATUS_FILE = ROOT / "tools" / "link-status.txt"
URL_RE = re.compile(r'(?:href|src|content)="(https?://[^"]+)"')
# Hosts that rate-limit or block scripted requests; a non-200 here is not proof
# of a dead link.
UNVERIFIABLE = ("linkedin.com", "researchgate.net", "npmjs.com", "fonts.googleapis.com",
                "fonts.gstatic.com", "storage.googleapis.com")


def collect() -> dict[str, set[str]]:
    found: dict[str, set[str]] = {}
    for page in sorted(ROOT.glob("*.html")):
        text = page.read_text(encoding="utf-8")
        text = re.sub(r"<(script|style)[^>]*>.*?</\1>", " ", text, flags=re.S)
        for raw in URL_RE.findall(text):
            url = html.unescape(raw).rstrip("/")
            found.setdefault(url, set()).add(page.name)
    for name in ("llms.txt", "llms-full.txt", "site.webmanifest", "robots.txt", "sitemap.xml"):
        path = ROOT / name
        if path.exists():
            for raw in URL_RE.findall(path.read_text(encoding="utf-8")):
                found.setdefault(html.unescape(raw).rstrip("/"), set()).add(name)
    return found


def probe(url: str) -> str:
    try:
        out = subprocess.run(
            ["curl", "-s", "-o", "/dev/null", "-L", "--max-time", "15",
             "-A", "Mozilla/5.0 (compatible; link-check)", "-w", "%{http_code}", url],
            capture_output=True, text=True, timeout=25,
        ).stdout.strip()
    except subprocess.TimeoutExpired:
        return "TIMEOUT"
    return out or "000"


def main() -> int:
    urls = collect()
    print(f"checking {len(urls)} unique external URLs\n")

    results: dict[str, str] = {}
    with concurrent.futures.ThreadPoolExecutor(max_workers=10) as pool:
        for url, code in zip(urls, pool.map(probe, urls)):
            results[url] = code

    bad, blocked, ok = [], [], 0
    for url in sorted(results):
        code = results[url]
        if code == "200":
            ok += 1
        elif code in ("404", "410") and not any(h in url for h in UNVERIFIABLE):
            # 404/410 mean gone. 403/999/TIMEOUT mean the host refused a
            # scripted request (ResearchGate, npm, LinkedIn do this), which is
            # not evidence that the link is dead.
            bad.append((code, url))
        else:
            blocked.append((code, url))

    for code, url in bad:
        where = ", ".join(sorted(urls[url]))
        print(f"  BROKEN  {code}  {url}\n            linked from: {where}")
    print(f"\n{ok} ok, {len(bad)} broken, {len(blocked)} unverifiable (bot-blocked)")
    for code, url in blocked:
        print(f"  UNKNOWN {code}  {url}")

    if "--write" in sys.argv:
        lines = ["# tools/link-status.txt - external link status",
                 "# generated by tools/check-links.py; UNVERIFIABLE hosts are marked"]
        lines += [f"{results[u]}\t{u}" for u in sorted(results)]
        STATUS_FILE.write_text("\n".join(lines) + "\n", encoding="utf-8")
        print(f"\nwrote {STATUS_FILE.relative_to(ROOT)}")

    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())